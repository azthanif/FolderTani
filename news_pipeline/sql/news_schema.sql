-- Skema modul berita untuk news_pipeline (versi ringkas): 3 tabel + 1 view.
-- Bila sebelumnya menjalankan versi lengkap (20261123_news_ner_summary.sql), jalankan dulu rollback_news_full.sql.

-- 1. Artikel + hasil NER + relevansi + ringkasan dalam satu baris
create table if not exists public.news_articles (
  id            int8 generated by default as identity primary key,
  url           text not null unique,
  media_name    text,
  title         text not null,
  publish_date  date,
  wilayah       text[] not null default '{}'  -- {'Garut'}, {'Cianjur'}, {'Nasional'}, atau gabungan; '{}' = tidak relevan
                check (wilayah <@ array['Garut','Cianjur','Nasional']),
  article_clean text,
  entities      jsonb not null default '[]',  -- [{"word","entity","score","start","end","field":"judul"|"isi"}], offset 0-based
  kategori      text,                         -- Harga & Pasar, Serapan & Stok, Pupuk & Sarana, ...
  summary       text,
  summary_model text,                         -- 'lead-2' atau 'idt5:<nama model>'
  created_at    timestamptz not null default now()
);
create index if not exists news_articles_wilayah_idx on public.news_articles using gin (wilayah);
create index if not exists news_articles_date_idx on public.news_articles (publish_date desc);

-- 2. Digest harian per kabupaten
create table if not exists public.news_digests (
  id           int8 generated by default as identity primary key,
  kabupaten    text not null check (kabupaten in ('Garut','Cianjur')),   -- isi: berita kabupaten + berita nasional
  digest_date  date not null,
  content      text not null,
  created_at   timestamptz not null default now(),
  unique (kabupaten, digest_date)
);

-- 3. Log kirim WA (cegah kirim ganda)
create table if not exists public.news_deliveries (
  digest_id  int8 not null references public.news_digests(id) on delete cascade,
  user_id    uuid not null references public.users(id) on delete cascade,
  status     text not null default 'SENT',    -- SENT / FAILED
  sent_at    timestamptz not null default now(),
  primary key (digest_id, user_id)
);

-- Penerima: hanya petani terdaftar di Garut/Cianjur
-- Ambil berita untuk digest X: select * from news_articles where wilayah && array[X,'Nasional'] and publish_date = current_date - 1;
create or replace view public.v_news_recipients
with (security_invoker = true) as
select id as user_id, phone, name,
       initcap(trim(regexp_replace(kabupaten, '^\s*(kabupaten|kab\.?)\s+', '', 'i'))) as kabupaten   -- "Kab. Garut" -> "Garut"
from public.users
where role = 'petani' and phone is not null
  and initcap(trim(regexp_replace(kabupaten, '^\s*(kabupaten|kab\.?)\s+', '', 'i'))) in ('Garut','Cianjur');

-- Akses web: hanya pengguna login
alter table public.news_articles   enable row level security;
alter table public.news_digests    enable row level security;
alter table public.news_deliveries enable row level security;
drop policy if exists auth_read on public.news_articles;
drop policy if exists auth_read on public.news_digests;
create policy auth_read on public.news_articles for select to authenticated using (true);
create policy auth_read on public.news_digests  for select to authenticated using (true);
